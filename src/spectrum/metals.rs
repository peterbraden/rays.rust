/// η and k of a named metal (`"Ag"`, `"Al"`, `"Au"`, `"Cu"`, `"CuZn"`), as interleaved tables.
pub fn named(name: &str) -> Option<(&'static [f64], &'static [f64])> {
    Some(match name {
        "Ag" => (&AG_ETA, &AG_K),
        "Al" => (&AL_ETA, &AL_K),
        "Au" => (&AU_ETA, &AU_K),
        "Cu" => (&CU_ETA, &CU_K),
        "CuZn" => (&CUZN_ETA, &CUZN_K),
        _ => return None,
    })
}

/// A piecewise-linear table of (λ, value) pairs at `lambda`, held constant beyond its ends.
pub fn lookup(table: &[f64], lambda: f64) -> f64 {
    let n = table.len() / 2;
    let x = |i: usize| table[2 * i];
    let y = |i: usize| table[2 * i + 1];
    if lambda <= x(0) {
        return y(0);
    }
    if lambda >= x(n - 1) {
        return y(n - 1);
    }
    let i = (0..n - 1).find(|&i| lambda < x(i + 1)).unwrap();
    let f = (lambda - x(i)) / (x(i + 1) - x(i));
    y(i) * (1. - f) + y(i + 1) * f
}
